-- Compatibility view reconstructs the existing API payload from categorized tables.
-- Session tokens are one-way hashes, so sessions are fetched separately below.
create or replace view public.casemate_entries with (security_invoker = true) as
 select 'auth:user:'||a.username as key,
  a.profile_data || jsonb_build_object('username',a.username,'displayName',a.display_name,'salt',c.salt,'passwordHash',c.password_hash) as value
 from public.user_accounts a join public.password_credentials c using(username)
 union all
 select 'records:'||r.username||':'||r.id,
  r.metadata || jsonb_build_object('id',r.id,'username',r.username,'fileName',r.file_name,'mimeType',r.mime_type,'size',r.size_bytes,'storagePath',r.storage_path,'extractedText',r.extracted_text,'extractionStatus',r.extraction_status,'createdAt',r.created_at)
 from public.uploaded_records r
 union all
 select r.legacy_key, r.metadata || jsonb_build_object('revision',r.revision,'generatedAt',r.generated_at,'summaryMode',r.summary_mode,'sections',r.sections,'sources',r.sources,'warnings',r.warnings)
 from public.medical_reports r
 union all
 select 'observations:'||e.username||':'||e.upload_id,
  jsonb_build_object('revision',e.revision,'warnings',e.warnings,'observations',coalesce((
   select jsonb_agg(jsonb_build_object('name',m.indicator_name,'value',m.value,'valueText',m.value_text,'unit',m.unit,'date',m.examination_date,'patient',m.patient_label,'reference',m.reference_range,'sourceId',m.source_id,'recordId',m.upload_id,'fileName',m.file_name,'mimeType',m.mime_type,'quote',m.quote) order by m.item_number)
   from public.measurements m where m.username=e.username and m.upload_id=e.upload_id
  ),'[]'::jsonb))
 from public.indicator_extractions e
 union all select s.key,s.value from public.app_settings s;
revoke all on public.casemate_entries from public,anon,authenticated;
grant select on public.casemate_entries to service_role;

create or replace function public.casemate_read_entry(p_key text) returns jsonb
language plpgsql security invoker set search_path = public as $$
declare output jsonb;
begin
 if starts_with(p_key,'auth:session:') then
  select jsonb_build_object('username',username,'displayName',display_name,'expiresAt',round(extract(epoch from expires_at)*1000)::bigint)
   into output from public.login_sessions
   where token_hash=encode(sha256(convert_to(substring(p_key from length('auth:session:')+1),'UTF8')),'hex');
 else
  select value into output from public.casemate_entries where key=p_key;
 end if;
 return output;
end $$;
create or replace function public.casemate_scan_entries(p_prefix text) returns jsonb
language sql security invoker set search_path = public as $$
 select coalesce(jsonb_agg(jsonb_build_object('key',key,'value',value) order by key),'[]'::jsonb)
 from public.casemate_entries where starts_with(key,p_prefix);
$$;

-- One RPC transaction updates each parent and all its child rows atomically.
create or replace function public.casemate_write_entry(p_key text,p_value jsonb) returns void
language plpgsql security invoker set search_path = public as $$
declare owner_name text; upload text; part jsonb; ordinal bigint; indicator bigint; normalized text;
begin
 if starts_with(p_key,'auth:user:') then
  owner_name=substring(p_key from length('auth:user:')+1);
  if owner_name<>p_value->>'username' then raise exception 'Account owner mismatch'; end if;
  insert into public.user_accounts(username,display_name,created_at,profile_data)
   values(owner_name,p_value->>'displayName',(p_value->>'createdAt')::timestamptz,p_value-'salt'-'passwordHash')
   on conflict(username) do update set display_name=excluded.display_name,created_at=excluded.created_at,profile_data=excluded.profile_data;
  insert into public.password_credentials(username,password_hash,salt) values(owner_name,p_value->>'passwordHash',p_value->>'salt')
   on conflict(username) do update set password_hash=excluded.password_hash,salt=excluded.salt;
 elsif starts_with(p_key,'auth:session:') then
  owner_name=p_value->>'username';
  insert into public.user_accounts(username,display_name) values(owner_name,coalesce(p_value->>'displayName',owner_name)) on conflict do nothing;
  insert into public.login_sessions(token_hash,username,display_name,expires_at)
   values(encode(sha256(convert_to(substring(p_key from length('auth:session:')+1),'UTF8')),'hex'),owner_name,p_value->>'displayName',to_timestamp((p_value->>'expiresAt')::numeric/1000))
   on conflict(token_hash) do update set username=excluded.username,display_name=excluded.display_name,expires_at=excluded.expires_at;
 elsif starts_with(p_key,'records:') then
  owner_name=split_part(p_key,':',2); upload=split_part(p_key,':',3);
  if owner_name<>p_value->>'username' or upload<>p_value->>'id' then raise exception 'Upload owner mismatch'; end if;
  insert into public.user_accounts(username,display_name) values(owner_name,owner_name) on conflict do nothing;
  if exists(select 1 from public.uploaded_records where username=owner_name and id=upload and extracted_text is distinct from p_value->>'extractedText') then
   delete from public.indicator_extractions where username=owner_name and upload_id=upload;
  end if;
  insert into public.uploaded_records(username,id,file_name,mime_type,size_bytes,storage_path,extracted_text,extraction_status,created_at,metadata)
   values(owner_name,upload,p_value->>'fileName',p_value->>'mimeType',(p_value->>'size')::bigint,p_value->>'storagePath',coalesce(p_value->>'extractedText',''),p_value->>'extractionStatus',(p_value->>'createdAt')::timestamptz,p_value)
   on conflict(username,id) do update set file_name=excluded.file_name,mime_type=excluded.mime_type,size_bytes=excluded.size_bytes,storage_path=excluded.storage_path,extracted_text=excluded.extracted_text,extraction_status=excluded.extraction_status,metadata=excluded.metadata;
  delete from public.uploaded_files where username=owner_name and upload_id=upload;
  for part,ordinal in select value, ordinality from jsonb_array_elements(case when jsonb_array_length(coalesce(p_value->'files','[]'))>0 then p_value->'files' else jsonb_build_array(p_value) end) with ordinality loop
   insert into public.uploaded_files(username,id,upload_id,file_number,file_name,mime_type,size_bytes,storage_path)
    values(owner_name,case when jsonb_array_length(coalesce(p_value->'files','[]'))>1 then upload||':file:'||ordinal else upload end,upload,ordinal,part->>'fileName',part->>'mimeType',(part->>'size')::bigint,part->>'storagePath');
  end loop;
 elsif starts_with(p_key,'report:') then
  owner_name=split_part(p_key,':',2); upload=nullif(split_part(p_key,':',3),'');
  insert into public.user_accounts(username,display_name) values(owner_name,owner_name) on conflict do nothing;
  insert into public.medical_reports(legacy_key,username,upload_id,revision,generated_at,summary_mode,sections,sources,warnings,metadata)
   values(p_key,owner_name,upload,p_value->>'revision',(p_value->>'generatedAt')::timestamptz,p_value->>'summaryMode',coalesce(p_value->'sections','{}'),coalesce(p_value->'sources','[]'),coalesce(p_value->'warnings','[]'),p_value)
   on conflict(legacy_key) do update set revision=excluded.revision,generated_at=excluded.generated_at,summary_mode=excluded.summary_mode,sections=excluded.sections,sources=excluded.sources,warnings=excluded.warnings,metadata=excluded.metadata;
 elsif starts_with(p_key,'observations:') then
  owner_name=split_part(p_key,':',2); upload=split_part(p_key,':',3);
  insert into public.indicator_extractions(username,upload_id,revision,warnings)
   values(owner_name,upload,p_value->>'revision',coalesce(p_value->'warnings','[]'))
   on conflict(username,upload_id) do update set revision=excluded.revision,warnings=excluded.warnings,indexed_at=now();
  delete from public.measurements where username=owner_name and upload_id=upload;
  for part,ordinal in select value,ordinality from jsonb_array_elements(coalesce(p_value->'observations','[]')) with ordinality loop
   if part->>'recordId'<>upload then raise exception 'Measurement upload mismatch'; end if;
   normalized=lower(regexp_replace(part->>'name','\s+','','g'));
   insert into public.indicators(normalized_name,source_name) values(normalized,part->>'name')
    on conflict(normalized_name) do update set source_name=public.indicators.source_name returning id into indicator;
   insert into public.measurements(username,upload_id,item_number,indicator_id,indicator_name,value,value_text,unit,examination_date,patient_label,reference_range,source_id,file_name,mime_type,quote)
    values(owner_name,upload,ordinal,indicator,part->>'name',(part->>'value')::numeric,part->>'valueText',coalesce(part->>'unit',''),nullif(part->>'date','')::date,coalesce(part->>'patient',''),coalesce(part->>'reference',''),part->>'sourceId',part->>'fileName',part->>'mimeType',part->>'quote');
  end loop;
 else
  insert into public.app_settings(key,value) values(p_key,p_value) on conflict(key) do update set value=excluded.value;
 end if;
end $$;
create or replace function public.casemate_delete_entry(p_key text) returns void
language plpgsql security invoker set search_path=public as $$
begin
 if starts_with(p_key,'auth:session:') then
  delete from public.login_sessions where token_hash=encode(sha256(convert_to(substring(p_key from length('auth:session:')+1),'UTF8')),'hex');
 elsif starts_with(p_key,'records:') then
  delete from public.uploaded_records where username=split_part(p_key,':',2) and id=split_part(p_key,':',3);
 elsif starts_with(p_key,'observations:') then
  delete from public.indicator_extractions where username=split_part(p_key,':',2) and upload_id=split_part(p_key,':',3);
 elsif starts_with(p_key,'report:') then
  delete from public.medical_reports where legacy_key=p_key;
 elsif starts_with(p_key,'auth:user:') then
  raise exception 'Account deletion requires a dedicated workflow';
 else
  delete from public.app_settings where key=p_key;
 end if;
end $$;
revoke all on function public.casemate_read_entry(text),public.casemate_scan_entries(text),public.casemate_write_entry(text,jsonb),public.casemate_delete_entry(text) from public,anon,authenticated;
grant execute on function public.casemate_read_entry(text),public.casemate_scan_entries(text),public.casemate_write_entry(text,jsonb),public.casemate_delete_entry(text) to service_role;

-- Backfill once, within this transaction; ordering preserves parents before children.
do $$
declare entry record; migrated bigint=0; total bigint;
begin
 if not exists(select 1 from public.migration_audits where migration_id='202610220001_split_business_tables') then
  select count(*) into total from public.kv_store_ba71e98d;
  for entry in select key,value from public.kv_store_ba71e98d order by
   case when starts_with(key,'auth:user:') then 0 when starts_with(key,'records:') then 1 when starts_with(key,'observations:') then 3 else 2 end,key loop
   perform public.casemate_write_entry(entry.key,entry.value);
   if public.casemate_read_entry(entry.key) is null then raise exception 'Migration verification failed for an entry'; end if;
   migrated=migrated+1;
  end loop;
  if migrated<>total then raise exception 'Migration row count mismatch'; end if;
  insert into public.migration_audits(migration_id,legacy_rows,migrated_rows) values('202610220001_split_business_tables',total,migrated);
 end if;
end $$;
